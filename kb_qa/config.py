"""
Knowledge Base QA 系统参数配置。

所有默认参数集中在这里管理。
- cli.py（命令行）和 website/qa_api/router.py（Web服务）都从此模块导入默认值。
- 如需调参，只需修改此文件即可两端同步生效。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class KBQADefaults:
    """KB_QA 问答系统的默认参数配置（最佳实践值）。

    这些值经过调优，在回答质量与运行速度/API消耗之间取得平衡。
    修改前请参考 doc/kb_qa_config.md 了解各参数含义。
    """

    # ════════════════════════════════════════════════════
    # 检索阶段参数
    # ════════════════════════════════════════════════════

    # 向量检索实际使用的 top_k
    # 从 survey 结果中取前 N 条用于后续分析
    # 值越大：检索越全面，但分析/合成的 LLM API 消耗越多
    vector_top_k: int = 40

    # BM25 检索实际使用的 top_k
    # 从 survey 结果中取前 N 条用于后续分析（仅作为向量的少量补充）
    bm25_top_k: int = 50

    # 向量检索相关性阈值 [0-1]
    # 低于此分数的向量检索结果被过滤，不参与后续合并
    # 值越低：召回越多但噪声也可能增多
    vector_score_threshold: float = 0.31

    # BM25 检索相关性阈值
    # 低于此分数的 BM25 检索结果被过滤
    bm25_score_threshold: float = 11.0

    # ════════════════════════════════════════════════════
    # 调查（Survey）阶段参数
    # （不参与实际分析，仅用于全面性评估）
    # ════════════════════════════════════════════════════

    # 向量检索 survey 阶段的 top_k
    # 仅用于评估"预估相关段总数"，不用于实际分析
    # 部署时可根据服务器内存调整（值越大预估越准）
    vector_survey_top_k: int = 1000

    # BM25 检索 survey 阶段的 top_k
    bm25_survey_top_k: int = 1000

    # ════════════════════════════════════════════════════
    # 上下文扩展参数
    # ════════════════════════════════════════════════════

    # 合并后的基础段前后各扩展多少条同直播同类型片段作为上下文
    # 值越大：每个片段的背景信息越多，但候选总量膨胀
    context_window: int = 5

    # ════════════════════════════════════════════════════
    # 分析阶段参数
    # ════════════════════════════════════════════════════

    # 每批交给 LLM 分析的候选段数量
    # 调大可以减少 API 调用次数，但单次上下文太长可能影响准确率
    # 目前方案 C 已跳过有用性分析阶段，此参数暂不生效
    analysis_batch_size: int = 100

    # ════════════════════════════════════════════════════
    # 合成阶段参数
    # ════════════════════════════════════════════════════

    # 合成时局部上下文的窗口大小
    # 每个片段在合成 prompt 中前后各取 N 条同直播同类片段作为局部上下文
    synthesis_context_window: int = 6

    # 有用段超过此数量时触发分批合成（当前未启用，全部候选保留）
    synthesis_batch_trigger_count: int = 100

    # 分批合成时每批的大小
    synthesis_batch_size: int = 50


# 单例实例，供外部导入使用
KB_QA_DEFAULTS = KBQADefaults()
